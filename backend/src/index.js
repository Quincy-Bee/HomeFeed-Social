import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import mongoose from 'mongoose';
import authRoutes from './routes/auth.js';
import postRoutes from './routes/posts.js';
const app = express();
app.use(cors({origin: process.env.CLIENT_ORIGIN || 'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.get('/api/health',(_req,res)=>res.json({ok:true,service:'homefeed-social-api'}));
app.use('/api/auth',authRoutes); app.use('/api/posts',postRoutes);
const port=process.env.PORT||5001;
if(!process.env.JWT_SECRET) console.warn('Set JWT_SECRET in backend/.env before using auth.');
mongoose.connect(process.env.MONGODB_URI||'mongodb://127.0.0.1:27017/homefeed_social_dev').then(()=>app.listen(port,()=>console.log(`API listening on ${port}`))).catch(e=>{console.error(e.message);process.exit(1)});
